-- New public signups ALWAYS start as vehicle_owner. Never trust client metadata to self-assign officer/admin.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, phone, role, province, district)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', ''),
    coalesce(new.raw_user_meta_data->>'phone', ''),
    'vehicle_owner',
    coalesce(new.raw_user_meta_data->>'province', 'Western'),
    coalesce(new.raw_user_meta_data->>'district', 'Colombo')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

