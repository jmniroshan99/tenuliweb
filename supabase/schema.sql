create table if not exists public.insurance_policies (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  vehicle_id uuid not null references public.vehicles(id) on delete cascade,
  provider text not null,
  policy_number text not null,
  insurance_type text not null,
  start_date date not null,
  expiry_date date not null,
  premium numeric(12,2) not null default 0,
  currency_code text not null default 'LKR',
  document_path text,
  renewed_from uuid references public.insurance_policies(id) on delete set null,
  created_by uuid references auth.users(id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id, policy_number),
  constraint valid_policy_dates check (expiry_date >= start_date),
  constraint lkr_currency_only check (currency_code = 'LKR')
