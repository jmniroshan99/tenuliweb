create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  phone text,
  role public.app_role not null default 'vehicle_owner',
  province text not null default 'Western',
  district text not null default 'Colombo',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Security-definer helper avoids duplicating role lookup logic in every policy.
create or replace function public.current_user_role()
returns public.app_role
language sql
stable
security definer
set search_path = public
as $$
  select role from public.profiles where id = auth.uid();
$$;

revoke all on function public.current_user_role() from public;
grant execute on function public.current_user_role() to authenticated;

create table if not exists public.vehicles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  owner_name text not null,
  registration_number text not null,
  vehicle_type text not null default 'Car',
  make text not null,
  model text not null,
  manufacture_year integer,
  chassis_number text,
  engine_number text,
  province text not null default 'Western',
  district text not null default 'Colombo',
  image_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
