// Build the repeatable SQL Editor installer from the authoritative additive upgrades.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const stripTransaction=s=>s.replace(/^begin;\s*$/mi,'').replace(/^commit;\s*$/mi,'');
const rental=stripTransaction(await readFile(new URL('supabase/RENTALS_UPGRADE.sql',root),'utf8'));
const repair=stripTransaction(await readFile(new URL('supabase/TENULI_REPAIRS_UPGRADE.sql',root),'utf8'));
const simple=stripTransaction(await readFile(new URL('supabase/TENULI_SIMPLE_BILLING_UPGRADE.sql',root),'utf8'));
const service=stripTransaction(await readFile(new URL('supabase/TENULI_SERVICE_DOCUMENTS_UPGRADE.sql',root),'utf8'));
const grouped=stripTransaction(await readFile(new URL('supabase/TENULI_GROUPED_BILLING_UPGRADE.sql',root),'utf8'));
const twoDocuments=stripTransaction(await readFile(new URL('supabase/TENULI_TWO_DOCUMENTS_UPGRADE.sql',root),'utf8'));
const modernPDFs=stripTransaction(await readFile(new URL('supabase/TENULI_MODERN_PDFS_UPGRADE.sql',root),'utf8'));
const pricingPhotos=stripTransaction(await readFile(new URL('supabase/TENULI_PRICING_PHOTOS_UPGRADE.sql',root),'utf8'));
const operationsBills=stripTransaction(await readFile(new URL('supabase/TENULI_OPERATIONS_BILL_UPGRADE.sql',root),'utf8'));
const blueLetterhead=stripTransaction(await readFile(new URL('supabase/TENULI_BLUE_LETTERHEAD_UPGRADE.sql',root),'utf8'));
const catalogue=stripTransaction(await readFile(new URL('supabase/TENULI_CATALOGUE_UPGRADE.sql',root),'utf8'));
const sql=`-- Tenuli Auto Care: enable Automart & Services on an existing insurance database.
-- Run this complete file in the EXISTING project's Supabase SQL Editor as the owner.
-- Back up first. Safe to repeat after a completed installation. Existing records,
-- issued documents and explicitly denied permissions are preserved.
-- Generated by scripts/build_automart_installer.mjs; edit the source migrations instead.
begin;
select pg_advisory_xact_lock(hashtextextended('tenuli-automart-install',0));
do $tenuli_install$
begin
 if to_regtype('public.app_role') is null or to_regclass('public.profiles') is null or
    to_regclass('public.vehicles') is null or to_regclass('public.permissions') is null or
    to_regclass('public.role_permissions') is null or to_regclass('public.user_permissions') is null or
    to_regclass('public.audit_logs') is null or
    to_regprocedure('public.current_user_role()') is null or
    to_regprocedure('public.current_user_is_active()') is null or
    to_regprocedure('public.has_permission(text)') is null or
    to_regprocedure('public.get_effective_permissions()') is null or
    to_regprocedure('public.permission_allowed_for_role(public.app_role,text)') is null then
   raise exception 'Existing insurance security setup is incomplete. Run PRECHECK_RENTALS.sql and resolve its prerequisites first. No Automart changes were committed.';
 end if;
 if to_regprocedure('public.rental_api(text,jsonb,uuid)') is null then
  if to_regclass('public.rental_customers') is not null or to_regclass('public.rental_bookings') is not null then
   raise exception 'A partial/custom rental installation exists. Review it before installing; this script does not overwrite it.';
  end if;
  execute $tenuli_rental_sql$
${rental}
$tenuli_rental_sql$;
 end if;
 if to_regprocedure('public.repair_api(text,jsonb,uuid)') is null then
  if to_regnamespace('repair_private') is not null then
   raise exception 'A partial/custom repair installation exists. Review it before installing; this script does not overwrite it.';
  end if;
  execute $tenuli_repair_sql$
${repair}
$tenuli_repair_sql$;
 end if;
 if to_regclass('repair_private.jobs') is null or to_regclass('repair_private.bills') is null or to_regclass('public.rental_business') is null then
  raise exception 'Module functions exist but required tables are missing. Review this installation; no changes were committed.';
 end if;
end
$tenuli_install$;
${simple}
${service}
${grouped}
${twoDocuments}
${modernPDFs}
${pricingPhotos}
${operationsBills}
${blueLetterhead}
${catalogue}
-- Restore only missing administrator defaults; do not override explicit denials.
insert into public.role_permissions(role,permission_key,allowed)
select 'administrator'::public.app_role, permission_key,true from public.permissions
where permission_key in('view_rentals','manage_rentals','view_billing','manage_billing','refund_payments',
'view_repairs','manage_repairs','view_repair_billing','manage_repair_payments','manage_shop_costs','view_job_profit','export_repair_reports')
on conflict(role,permission_key) do nothing;
notify pgrst, 'reload schema';
commit;
select 'Automart database installed. Click Check access again in the app, or sign out and back in.' as next_step,
 to_regprocedure('public.rental_api(text,jsonb,uuid)') is not null as rentals_installed,
 to_regprocedure('public.repair_api(text,jsonb,uuid)') is not null as repairs_installed;
`;
await writeFile(new URL('supabase/ENABLE_AUTOMART.sql',root),sql);
await mkdir(new URL('insuredrive-web/public/setup/',root),{recursive:true});
await writeFile(new URL('insuredrive-web/public/setup/ENABLE_AUTOMART.sql',root),sql);
console.log('Automart setup SQL ready. Existing records and explicit permission denials are preserved.');
